// 자동 추정이 실패했거나 틀렸을 때 사람이 직접 시작할 수 있는 기본 골격 (React 의존 없음)
// 전신 정면 사람을 가정한 비율 배치. 사용자가 점을 드래그해서 그림에 맞춘다.
// 이름·id는 App의 JOINTS와 같아야 한다.
import type { JointPt } from './jointMerge'

const NAMES: Record<number, string> = {
  0: '코', 11: '왼쪽 어깨', 12: '오른쪽 어깨', 13: '왼쪽 팔꿈치', 14: '오른쪽 팔꿈치',
  15: '왼쪽 손목', 16: '오른쪽 손목', 23: '왼쪽 골반', 24: '오른쪽 골반',
  25: '왼쪽 무릎', 26: '오른쪽 무릎', 27: '왼쪽 발목', 28: '오른쪽 발목',
  19: '왼쪽 손끝', 20: '오른쪽 손끝', 31: '왼쪽 발끝', 32: '오른쪽 발끝',
}

// 이미지 높이 h 기준의 비율. 반폭은 높이 비율(dx)이고 이미지 중앙 x가 기준.
// [id, dx(중앙에서 화면 오른쪽이 +), y]
const LAYOUT: [number, number, number][] = [
  [0, 0, 0.1],
  [11, 0.09, 0.22], [12, -0.09, 0.22],
  [13, 0.13, 0.36], [14, -0.13, 0.36],
  [15, 0.16, 0.49], [16, -0.16, 0.49],
  [19, 0.17, 0.54], [20, -0.17, 0.54],
  [23, 0.05, 0.5], [24, -0.05, 0.5],
  [25, 0.06, 0.7], [26, -0.06, 0.7],
  [27, 0.065, 0.9], [28, -0.065, 0.9],
  [31, 0.09, 0.95], [32, -0.09, 0.95],
]

// MediaPipe 기준 왼쪽 관절(11/13/15/19/23/25/27/31)은 정면 그림에서 이미지의 오른쪽(x가 큼)에 있다.
export function defaultSkeleton(w: number, h: number): JointPt[] {
  const cx = w / 2
  const clamp = (v: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, v))
  return LAYOUT.map(([id, dx, fy]) => ({
    id,
    name: NAMES[id],
    x: clamp(cx + dx * h, 4, w - 4),
    y: clamp(fy * h, 4, h - 4),
    source: 'auto' as const,
  }))
}
